"""Pack the workshop's rigid fox skin for both targets, using only Python's stdlib.

Geometry stays indexed and shared. Each draw group contains one joint and one
material so the existing meadow shader can pose it with a single matrix.
"""
import json
import math
from pathlib import Path
import struct

ROOT = Path(__file__).resolve().parents[1]
ASSET = ROOT / "assets/fox"
FORMAT = {5121: "B", 5123: "H", 5125: "I", 5126: "f"}
WIDTH = {"SCALAR": 1, "VEC3": 3, "VEC4": 4, "MAT4": 16}


def load_glb(path):
    data = path.read_bytes()
    if struct.unpack_from("<4sII", data) != (b"glTF", 2, len(data)):
        raise ValueError("Expected a complete GLB 2.0 export")
    length, kind = struct.unpack_from("<I4s", data, 12)
    if kind != b"JSON" or data[24+length:28+length] != b"BIN\0":
        raise ValueError("Expected embedded JSON and BIN chunks")
    return json.loads(data[20:20+length]), data[28+length:]


def pack():
    manifest = json.loads((ASSET / "fox.asset.json").read_text())
    if [manifest[k] for k in ("version", "units", "up", "forward")] != [1, "metres", "+Y", "+Z"]:
        raise ValueError("Incompatible socket manifest")
    gltf, blob = load_glb(ASSET / manifest["model"])

    def values(index):
        accessor = gltf["accessors"][index]
        view = gltf["bufferViews"][accessor["bufferView"]]
        row = struct.Struct("<" + FORMAT[accessor["componentType"]] * WIDTH[accessor["type"]])
        start = view.get("byteOffset", 0) + accessor.get("byteOffset", 0)
        stride = view.get("byteStride", row.size)
        return [row.unpack_from(blob, start + i * stride) for i in range(accessor["count"])]

    skin, = gltf["skins"]
    names = [gltf["nodes"][i]["name"] for i in skin["joints"]]
    sockets = manifest["sockets"]
    # Recover model-space joint origins from rigid inverse bind matrices.
    pivots = {}
    for name, m in zip(names, values(skin["inverseBindMatrices"]), strict=True):
        pivots[name] = [-sum(m[i*4+j] * m[12+j] for j in range(3)) for i in range(3)]
    def joint(name):
        return name.replace(".", "_")
    def vector(v):
        return "{" + ", ".join(f"{x:.8f}" for x in v) + "}"

    vertices, indices, groups = bytearray(), bytearray(), []
    mesh, = gltf["meshes"]
    for primitive in mesh["primitives"]:
        attrs = primitive["attributes"]
        pos, normal, ids, weights = [values(attrs[k]) for k in ("POSITION","NORMAL","JOINTS_0","WEIGHTS_0")]
        triangles = values(primitive["indices"])
        batches = {}
        for i in range(0, len(triangles), 3):
            tri = [t[0] for t in triangles[i:i+3]]
            bones = set()
            for v in tri:
                slot = max(range(4), key=weights[v].__getitem__)
                if weights[v][slot] < .99999:
                    raise ValueError("Fox adapter requires rigid vertex weights")
                bones.add(ids[v][slot])
            if len(bones) != 1:
                raise ValueError("Triangle spans multiple joints")
            batches.setdefault(names[bones.pop()], []).extend(tri)
        material = gltf["materials"][primitive["material"]]["pbrMetallicRoughness"]
        rgb = material["baseColorFactor"][:3]
        color = [round(255 * (12.92*x if x <= .0031308 else 1.055*x**(1/2.4)-.055)) for x in rgb] + [255]
        for name, batch in batches.items():
            unique = dict.fromkeys(batch)
            remap = {v: i for i,v in enumerate(unique)}
            first, offset = len(vertices)//24, len(indices)//2
            for v in unique:
                vertices.extend(struct.pack("<6f", *pos[v], *normal[v]))
            for v in batch:
                indices.extend(struct.pack("<H", remap[v]))
            groups.append(f"    {{.{joint(name)}, {first}, {len(unique)}, {offset}, {len(batch)}, {str(color).replace('[','{').replace(']','}')}}},")

    anim, = [a for a in gltf["animations"] if a["name"] == "tail_sweep"]
    channel, = [c for c in anim["channels"] if c["target"] == {"node": skin["joints"][names.index("tail")], "path": "rotation"}]
    sampler = anim["samplers"][channel["sampler"]]
    times = [v[0] for v in values(sampler["input"])]
    angles = []
    for x,y,z,w in values(sampler["output"]):
        if abs(x)+abs(y)>1e-5:
            raise ValueError("Expected tail swing about Blender Z")
        angles.append(2*math.atan2(z,w))
    if sampler["interpolation"] != "LINEAR" or len(times)<2:
        raise ValueError("Expected sampled tail sweep")
    lines = ["// Generated by tools/pack_fox.py from assets/fox.", "package game", "",
             "Fox_Joint :: enum {" + ", ".join(map(joint,names)) + "}",
             "FOX_PIVOT := [Fox_Joint]Vec3{"]
    lines.extend(f"    .{joint(n)} = {vector(pivots[n])}," for n in names)
    lines += ["}", f"FOX_MOUTH :: Fox_Joint.{joint(sockets['mouth'])}",
              f"FOX_GRIP :: Fox_Joint.{joint(sockets['tail_grip'])}",
              "FOX_SWEEP := [?][2]f32{"]
    lines.extend("    "+vector((t-times[0],a))+"," for t,a in zip(times,angles,strict=True))
    lines += ["}", "FOX_GROUPS := [?]Fox_Group{", *groups, "}", ""]
    (ASSET/"vertices.bin").write_bytes(vertices)
    (ASSET/"indices.bin").write_bytes(indices)
    (ROOT/"src/game/fox_asset.odin").write_text("\n".join(lines))


if __name__ == "__main__":
    pack()
